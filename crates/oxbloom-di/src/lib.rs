//! Singleton dependency injection for Oxbloom.
//!
//! Register types with a [`ContainerBuilder`] (`#[component]` structs, ready-made instances,
//! `factory` closures, typed `bean` functions or a `#[configuration]` impl), then call
//! [`ContainerBuilder::build`] to create every eager singleton in dependency order. Wiring
//! errors (a missing or ambiguous dependency, a cycle, a duplicate registration, a failing
//! constructor) are returned by `build()` as a [`DiError`].
//!
//! A dependency is requested in one of these shapes, as a `#[component]` field, a `bean`
//! parameter or through [`Resolver`] and [`Container`]:
//!
//! - `Arc<T>` or `Arc<dyn Trait>`: exactly one provider, or the single `primary` one;
//! - `Option<Arc<..>>`: `None` when nothing provides the key;
//! - `Vec<Arc<..>>`: every provider, sorted by `order` and then by registration order.
//!
//! A registration offers itself as a trait object with `provides`. Modifiers (`provides`,
//! `primary`, `order`, `lazy`, `profile`, `profile_not`, `post_construct`, `pre_destroy`,
//! `lifecycle`) apply to the registration just before them. [`Container::shutdown`] runs the
//! `pre_destroy` hooks in reverse creation order; dropping a container does not.
//!
//! Conditions (`condition`, `on_bean`, `on_missing_bean`, `on_property`, `on_property_value`,
//! `on_property_value_or_missing`) are modifiers too: `build()` keeps a registration only when
//! all of its conditions match, judged against the registrations kept before it and the
//! properties of an [`Environment`]. [`ContainerBuilder::build_with_report`] and
//! [`Container::condition_report`] give the [`ConditionReport`] of what was evaluated and why.
//! [`ContainerBuilder::group`] puts several registrations under one set of [`Conditions`],
//! decided once for the whole group.
//!
//! # Examples
//!
//! ```
//! use std::sync::{Arc, Mutex};
//! use oxbloom_di::{ContainerBuilder, DiError, Lifecycle, component};
//!
//! trait Notifier: Send + Sync { fn name(&self) -> &'static str; }
//!
//! #[component(provides(dyn Notifier), order = 2)]
//! struct Email;
//! impl Notifier for Email { fn name(&self) -> &'static str { "email" } }
//!
//! #[component(provides(dyn Notifier), primary, order = 1)]
//! struct Sms;
//! impl Notifier for Sms { fn name(&self) -> &'static str { "sms" } }
//!
//! // A lazy bean with lifecycle hooks: created on first use, destroyed by `shutdown`.
//! #[derive(Default)]
//! struct Outbox { sent: Mutex<Vec<String>>, open: Mutex<bool> }
//! impl Lifecycle for Outbox {
//!     fn post_construct(&self) -> Result<(), DiError> {
//!         *self.open.lock().unwrap() = true;
//!         Ok(())
//!     }
//!     fn pre_destroy(&self) {
//!         *self.open.lock().unwrap() = false;
//!     }
//! }
//!
//! // A plain function as a bean: its parameters are injected.
//! struct Alerts { primary: Arc<dyn Notifier>, all: Vec<Arc<dyn Notifier>>, outbox: Arc<Outbox> }
//! fn alerts(
//!     primary: Arc<dyn Notifier>,
//!     all: Vec<Arc<dyn Notifier>>,
//!     outbox: Arc<Outbox>,
//! ) -> Alerts {
//!     Alerts { primary, all, outbox }
//! }
//!
//! let container = ContainerBuilder::new()
//!     .component::<Email>()
//!     .component::<Sms>()
//!     .bean(Outbox::default).lazy().lifecycle::<Outbox>()
//!     .bean(alerts).lazy()
//!     .build()?;
//!
//! // `primary` picks one of several providers; `Vec` gets all of them, by `order`.
//! let alerts = container.get::<Alerts>()?; // creates Alerts and, through it, Outbox
//! assert_eq!(alerts.primary.name(), "sms");
//! let names: Vec<_> = alerts.all.iter().map(|n| n.name()).collect();
//! assert_eq!(names, ["sms", "email"]);
//! assert!(*alerts.outbox.open.lock().unwrap());
//! alerts.outbox.sent.lock().unwrap().push("hello".into());
//!
//! // Shutdown runs `pre_destroy`; afterwards the container refuses requests.
//! let report = container.shutdown();
//! assert_eq!(report.destroyed, 1);
//! assert!(!*alerts.outbox.open.lock().unwrap());
//! assert!(matches!(container.get::<Alerts>(), Err(DiError::ShutDown)));
//! # Ok::<(), DiError>(())
//! ```

