//! Task scheduling and retry for Oxbloom: fixed-rate, fixed-delay and cron triggers, the
//! [`Scheduler`] that runs [`Task`]s on tokio when they fire, and the [`RetryPolicy`] that
//! runs a failed async operation again.
//!
//! A [`Trigger`] decides when a task runs next. [`Trigger::fixed_rate`] measures the period
//! from the start of the last run, [`Trigger::fixed_delay`] from its end, and [`Trigger::cron`]
//! takes a six-field cron expression (seconds first) evaluated in a [`Zone`] (UTC by default,
//! or an IANA zone name).
//!
//! A [`RetryPolicy`] calls an operation up to `max_attempts` times and sleeps between the
//! attempts with [`Backoff::Fixed`] or [`Backoff::Exponential`] backoff, capped at
//! `max_delay` and spread by a [`Jitter`]. When the attempts run out, the last error is
//! returned; a panic is never retried. [`defaults`] holds the process-wide values that
//! [`set_defaults`] stores and [`reset_defaults`] restores to the built-in ones.
//!
//! # Examples
//!
//! ```
//! use std::time::{Duration, UNIX_EPOCH};
//! use oxbloom_tasks::{Trigger, Zone};
//!
//! let trigger = Trigger::cron("0 30 * * * *", Zone::Utc)?;
//! let now = UNIX_EPOCH + Duration::from_secs(10 * 60);
//! assert_eq!(trigger.next(None, None, now), Some(UNIX_EPOCH + Duration::from_secs(30 * 60)));
//! # Ok::<(), oxbloom_tasks::TriggerError>(())
//! ```

